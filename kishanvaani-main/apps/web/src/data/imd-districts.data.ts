export type RegionName = "North" | "South" | "East" | "West" | "Central" | "North-East" | "Islands";

export interface ImdDistrictProfile {
  id: string;
  region: RegionName;
  state: string;
  district: string;
  agroZone: string;
  lat: number;
  lon: number;
  elevationMeters: number;
  primaryCrops: string[];
  normalAnnualRainfallMm: number;
  currentObs: {
    temperature: number;
    feelsLike: number;
    minTemp: number;
    maxTemp: number;
    condition: string;
    humidity: number;
    windSpeed: number;
    windDirection: string;
    pressureHpa: number;
    uvIndex: number;
    rainfall24hMm: number;
  };
  warning: {
    alertLevel: "GREEN" | "YELLOW" | "ORANGE" | "RED";
    levelName: string;
    phenomenon: string;
    severity: "NONE" | "MODERATE" | "SEVERE" | "EXTREME";
    validUntil: string;
    impactOnFarming: string;
    farmerAction: string;
  };
  nowcast: {
    station: string;
    radarStation: string;
    status: "CLEAR" | "CONVECTIVE_CELLS" | "THUNDERSTORM_WATCH";
    headline: string;
    validForHours: number;
    gustSpeedKmh: number;
    rainfallExpected3hMm: number;
    satelliteObservation: string;
    issuedAt: string;
  };
  agromet: {
    general: string;
    sprayWindowSafe: boolean;
    sprayReason: string;
    irrigationStatus: "ADEQUATE" | "DEFICIT" | "SURPLUS";
    irrigationAdvice: string;
    crops: Array<{
      crop: string;
      stage: string;
      recommendation: string;
      pestDiseaseRisk: string;
      controlMeasure?: string;
    }>;
    livestock: string;
  };
}

// Helper to create consistent district definitions
function createDistrict(params: {
  region: RegionName;
  state: string;
  district: string;
  agroZone: string;
  lat: number;
  lon: number;
  elevationMeters: number;
  primaryCrops: string[];
  rainfallMm: number;
  temp: number;
  minTemp: number;
  maxTemp: number;
  condition: string;
  humidity: number;
  windSpeed: number;
  windDir: string;
  alertLevel?: "GREEN" | "YELLOW" | "ORANGE" | "RED";
  phenomenon?: string;
  action?: string;
  radar: string;
  generalAdv: string;
  spraySafe: boolean;
  sprayReason: string;
  irrigStatus: "ADEQUATE" | "DEFICIT" | "SURPLUS";
  irrigAdvice: string;
  crops: Array<{ crop: string; stage: string; rec: string; pestRisk: string; control?: string }>;
  livestock: string;
}): ImdDistrictProfile {
  const alert = params.alertLevel || "GREEN";
  const levelNames: Record<string, string> = {
    GREEN: "No Warning (All Clear)",
    YELLOW: "Watch (Be Updated)",
    ORANGE: "Alert (Be Prepared)",
    RED: "Warning (Take Action)",
  };

  const id = `${params.state}_${params.district}`.replace(/[\s()&'-]+/g, "_");

  return {
    id,
    region: params.region,
    state: params.state,
    district: params.district,
    agroZone: params.agroZone,
    lat: params.lat,
    lon: params.lon,
    elevationMeters: params.elevationMeters,
    primaryCrops: params.primaryCrops,
    normalAnnualRainfallMm: params.rainfallMm,
    currentObs: {
      temperature: params.temp,
      feelsLike: Math.round((params.temp + (params.humidity > 60 ? 1.5 : -0.5)) * 10) / 10,
      minTemp: params.minTemp,
      maxTemp: params.maxTemp,
      condition: params.condition,
      humidity: params.humidity,
      windSpeed: params.windSpeed,
      windDirection: params.windDir,
      pressureHpa: 1012,
      uvIndex: params.temp > 32 ? 8 : 6,
      rainfall24hMm: alert === "ORANGE" ? 18.5 : alert === "YELLOW" ? 2.5 : 0,
    },
    warning: {
      alertLevel: alert,
      levelName: levelNames[alert],
      phenomenon: params.phenomenon || "Normal atmospheric conditions favorable for agriculture",
      severity: alert === "RED" ? "EXTREME" : alert === "ORANGE" ? "SEVERE" : alert === "YELLOW" ? "MODERATE" : "NONE",
      validUntil: "Next 48 Hours",
      impactOnFarming: alert === "GREEN" ? "No adverse impact; suitable for routine farm operations." : "Variable moisture/wind impact on standing crops.",
      farmerAction: params.action || "Continue routine intercultural and irrigation operations.",
    },
    nowcast: {
      station: `${params.district} Agro-Met Observatory`,
      radarStation: params.radar,
      status: alert === "ORANGE" ? "THUNDERSTORM_WATCH" : alert === "YELLOW" ? "CONVECTIVE_CELLS" : "CLEAR",
      headline: alert === "GREEN" ? `Fair weather across ${params.district} and adjoining areas.` : `Localized clouds over ${params.district} tract.`,
      validForHours: 3,
      gustSpeedKmh: Math.round(params.windSpeed * 1.5),
      rainfallExpected3hMm: alert === "ORANGE" ? 12 : alert === "YELLOW" ? 2 : 0,
      satelliteObservation: `INSAT-3DR: ${params.condition} over ${params.state}.`,
      issuedAt: "10:30 AM",
    },
    agromet: {
      general: params.generalAdv,
      sprayWindowSafe: params.spraySafe,
      sprayReason: params.sprayReason,
      irrigationStatus: params.irrigStatus,
      irrigationAdvice: params.irrigAdvice,
      crops: params.crops.map((c) => ({
        crop: c.crop,
        stage: c.stage,
        recommendation: c.rec,
        pestDiseaseRisk: c.pestRisk,
        controlMeasure: c.control,
      })),
      livestock: params.livestock,
    },
  };
}

