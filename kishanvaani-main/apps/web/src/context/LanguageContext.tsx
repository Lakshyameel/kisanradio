/**
 * Synchronize HTML document lang attribute with active regional language
 */
function syncDocumentLanguage(langCode: LanguageCode) {
  if (typeof document !== "undefined") {
    document.documentElement.lang = langCode;
  }
}

interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  translateContent: (text?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    return (localStorage.getItem("kv_language") as LanguageCode) || "hi";
  });

  // Apply on mount and on change
  useEffect(() => {
    syncDocumentLanguage(language);
  }, [language]);

  const setLanguage = useCallback((lang: LanguageCode) => {
    localStorage.setItem("kv_language", lang);
    setLanguageState(lang);
    syncDocumentLanguage(lang);
  }, []);

  // UI dictionary translation
  const t = useCallback(
    (key: string, fallback?: string): string => {
      const match = uiTranslations[language]?.[key];
      if (match) return match;

      const fallbackMatch = uiTranslations.en?.[key];
      if (fallbackMatch) return fallbackMatch;

      return fallback || key;
    },
    [language]
  );

  // Dynamic content translation for titles, summaries, crop names
  const translateContent = useCallback(
    (text?: string): string => {
      if (!text) return "";
      if (language === "en") return text;

      // 1. Direct match in content dictionary
      if (contentTranslationMap[text]?.[language]) {
        return contentTranslationMap[text][language];
      }

      // 2. Direct match in UI dictionary
      if (uiTranslations[language]?.[text]) {
        return uiTranslations[language][text];
      }

      // 3. Match terms dictionary for crops or weather conditions
      const terms = termsDictionary[language];
      if (terms) {
        if (terms[text]) return terms[text];

        // Search for contained crop names
        let replaced = text;
        let didReplace = false;
        for (const [enTerm, localTerm] of Object.entries(terms)) {
          if (replaced.includes(enTerm)) {
            replaced = replaced.split(enTerm).join(localTerm);
            didReplace = true;
          }
        }
        if (didReplace) return replaced;
      }

      return text;
    },
    [language]
  );

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, translateContent }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
