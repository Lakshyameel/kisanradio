  /**
   * Get AGMARKNET prices with filtering via LiveMandiService
   */
  public static async getPrices(query: {
    state?: string;
    district?: string;
    commodity?: string;
    market?: string;
    search?: string;
    limit?: number;
    offset?: number;
  }) {
    const live = await LiveMandiService.getLiveMandiPrices({
      state: query.state,
      district: query.district,
      commodity: query.commodity,
      search: query.search || query.market,
      limit: query.limit,
      offset: query.offset,
    });

    const prices: AgmarknetRecord[] = live.records.map((r, idx) => ({
      id: `agmarknet-${r.state}-${r.market}-${r.commodity}-${idx}`,
      state: r.state,
      district: r.district,
      market: r.market,
      commodity: r.commodity,
      variety: r.variety,
      grade: "FAQ",
      arrivalDate: r.arrivalDate || "",
      arrivals: 0,
      minPrice: r.minPrice,
      maxPrice: r.maxPrice,
      modalPrice: r.modalPrice,
      trend: r.trend,
      source: "AGMARKNET",
    }));

    return {
      source: "AGMARKNET",
      agency: "Directorate of Marketing & Inspection (DMI), Ministry of Agriculture & Farmers Welfare, Govt. of India",
      portal: "https://agmarknet.gov.in",
      count: prices.length,
      total: live.total,
      prices,
    };
  }

  /**
   * Get distinct commodities reporting on AGMARKNET via LiveMandiService
   */
  public static async getCommodities(): Promise<string[]> {
    const live = await LiveMandiService.getLiveMandiPrices({ limit: 1000 });
    return Array.from(new Set<string>(live.records.map((i) => i.commodity))).sort();
  }

  /**
   * Get distinct states and districts reporting on AGMARKNET via LiveMandiService
   */
  public static async getStatesAndDistricts() {
    const live = await LiveMandiService.getLiveMandiPrices({ limit: 1000 });
    const states = Array.from(new Set<string>(live.records.map((i) => i.state))).sort();
    const districts = Array.from(new Set<string>(live.records.map((i) => i.district))).sort();
    const markets = Array.from(new Set<string>(live.records.map((i) => i.market))).sort();

    return {
      states,
      districts,
      markets,
    };
  }

  /**
   * Get high level market summary via LiveMandiService
   */
  public static async getSummary() {
    const stats = await LiveMandiService.getLiveStats();
    return {
      activeMandisCount: stats.uniqueMarkets,
      reportingStates: stats.uniqueStates,
      totalArrivalsQuintals: null,
      marketTrends: {
        upward: 0,
        downward: 0,
        stable: stats.totalRecords,
      },
      lastUpdated: stats.lastRefreshed,
    };
  }

